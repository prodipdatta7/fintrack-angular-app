const PALETTE = [
    '#4F46E5', '#059669', '#2563EB', '#0891B2', '#16A34A',
    '#7C3AED', '#D97706', '#0D9488', '#EC4899', '#10B981',
    '#F59E0B', '#EA580C', '#0284C7', '#8B5CF6', '#E11D48',
];

export function getIconColor(iconName: string | null | undefined): string {
    if (!iconName) return '#6366F1';
    if (ICON_COLOR_MAP[iconName]) return ICON_COLOR_MAP[iconName];
    let hash = 0;
    for (let i = 0; i < iconName.length; i++) {
        hash = (hash << 5) - hash + iconName.charCodeAt(i);
        hash |= 0;
    }
    return PALETTE[Math.abs(hash) % PALETTE.length];
}
